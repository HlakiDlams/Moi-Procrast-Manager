"""Slices design/icons-source.png (black icons on transparent, 7 rows) into
src/icons/png/<name>.png and writes src/icons/index.tsx.
Run from the repo root:  python3 design/make-ui-icons.py"""
from PIL import Image, ImageDraw, ImageChops
import os, re

SRC = 'design/icons-source.png'
OUT = 'src/icons/png'
CANVAS, SCALE = 120, 2  # every icon is centred on the same canvas so relative sizes are kept

# sheet order, row by row. None = not used by the app (duplicate or spare).
NAMES = [
    ['Sun', 'BookOpen', 'CalendarDays', 'HeartPulse', 'Gamepad2', 'Dumbbell', 'ScanText', 'UserRound', 'AlarmClock', 'Settings', 'LayoutGrid'],
    ['Flame', 'Star', 'Badge', 'Heart', 'HeartFill', 'TriangleAlert', 'Trophy', 'Crown', 'Lock', 'Check', 'CircleCheck'],
    ['CircleMinus', 'CircleX', 'EyeOff', None, 'PencilLine', 'Coffee', 'Utensils', None, None, 'Sparkles', 'HandHeart', 'Moon', 'Pin'],
    ['Droplet', 'EggFried', 'Sandwich', 'Soup', 'Apple', 'Flower2', 'Frown', 'Annoyed', 'Meh', 'Smile', 'Laugh'],
    ['Scale', None, 'Timer', None, 'Wallet', 'Languages', 'Target', 'Backpack', 'GraduationCap', 'Briefcase', 'BriefcaseBusiness', 'Globe', None],
    ['Play', 'X', 'Trash2', 'Plus', 'ChevronLeft', 'ChevronRight', 'ChevronsRight', 'Volume2', None, 'Wind', 'GripVertical', 'Download'],
    ['Upload', 'RotateCw', 'Bell', None, 'CloudFog', None, 'Pause', None, 'Pencil', 'SquarePen'],
]
# Download = the app's Export button (arrow leaving the tray); Upload = Import (arrow into the tray)
FILLED = ['Flame', 'Star', 'Droplet', 'Play']  # solid versions made by filling the outline
ROTATED = {'ChevronDown': ('ChevronRight', -90)}

im = Image.open(SRC).convert('RGBA')
a = im.getchannel('A')
W, H = a.size
px = a.load()

rows, on = [], False
for y in range(H):
    has = any(px[x, y] > 40 for x in range(0, W, 2))
    if has and not on:
        s, on = y, True
    if not has and on:
        rows.append((s, y))
        on = False
assert len(rows) == len(NAMES), len(rows)

os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    os.remove(os.path.join(OUT, f))
made = {}


def kebab(n):
    return re.sub(r'(?<!^)(?=[A-Z0-9])', '-', n).lower()


def save(name, alpha):
    big = alpha.resize((CANVAS * SCALE, CANVAS * SCALE), Image.LANCZOS)
    big = big.point(lambda v: max(0, min(255, round((v - 96) * 255 / 64))))  # re-sharpen the edge after upscaling
    out = Image.new('RGBA', big.size, (0, 0, 0, 0))
    out.putalpha(big)
    out.save(f'{OUT}/{kebab(name)}.png', optimize=True)
    made[name] = alpha


for (y0, y1), names in zip(rows, NAMES):
    col = [any(px[x, y] > 40 for y in range(y0, y1)) for x in range(W)]
    segs, on = [], False
    for x in range(W):
        if col[x] and not on:
            s, on = x, True
        if not col[x] and on:
            segs.append([s, x])
            on = False
    groups = [[segs[0]]]
    for s in segs[1:]:
        if s[0] - groups[-1][-1][1] < 22:
            groups[-1].append(s)
        else:
            groups.append([s])
    while len(groups) < len(names):  # icons drawn close together: split at the widest inner gap
        gi = max(range(len(groups)), key=lambda i: groups[i][-1][1] - groups[i][0][0] if len(groups[i]) > 1 else -1)
        g = groups[gi]
        k = max(range(1, len(g)), key=lambda i: g[i][0] - g[i - 1][1])
        groups[gi : gi + 1] = [g[:k], g[k:]]
    assert len(groups) == len(names), (len(groups), names)
    for g, name in zip(groups, names):
        if not name:
            continue
        cell = a.crop((g[0][0], y0, g[-1][1], y1))
        cell = cell.crop(cell.point(lambda v: 255 if v > 40 else 0).getbbox())
        assert max(cell.size) <= CANVAS, (name, cell.size)
        sq = Image.new('L', (CANVAS, CANVAS), 0)
        sq.paste(cell, ((CANVAS - cell.width) // 2, (CANVAS - cell.height) // 2))
        save(name, sq)

for name in FILLED:
    src = made[name]
    inv = src.point(lambda v: 0 if v > 110 else 255)  # white = not ink
    ImageDraw.floodfill(inv, (0, 0), 128)  # mark the outside
    inside = inv.point(lambda v: 255 if v == 255 else 0)
    save(name + 'Fill', ImageChops.lighter(src, inside))
for name, (base, deg) in ROTATED.items():
    save(name, made[base].rotate(deg))

SOLID = {'Heart': 'HeartFill', **{n: n + 'Fill' for n in FILLED}}
names = sorted(n for n in made if not n.endswith('Fill'))
lines = [
    '// Generated by design/make-ui-icons.py from design/icons-source.png. Do not edit by hand.',
    "import { makeIcon } from './Icon'",
]
for n in sorted(made):
    lines.append(f"import {n[0].lower() + n[1:]}Url from './png/{kebab(n)}.png'")
lines.append('')
lines.append("export type { IconProps, LucideIcon } from './Icon'")
for n in names:
    v = n[0].lower() + n[1:]
    solid = f", {SOLID[n][0].lower() + SOLID[n][1:]}Url" if n in SOLID else ''
    lines.append(f'export const {n} = makeIcon({v}Url{solid})')
open('src/icons/index.tsx', 'w').write('\n'.join(lines) + '\n')
print(len(made), 'icons')
